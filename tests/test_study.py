import json
from pathlib import Path

import pytest

from ocp import config
from ocp.lab import study
from ocp.sim.evaluate import run_design
from ocp.world.world import build_site

ROOT = Path(__file__).resolve().parents[1]


def test_kit_beats_as_is_with_the_same_luck() -> None:
    site = build_site(3, "ch-bank")
    d = config.designs()["designs"]
    a = run_design(site, d["as_is"]["switches"])
    k = run_design(site, d["kit"]["switches"])
    assert k["reportable_escalated_share"] > a["reportable_escalated_share"] and k["backlog_at_end"] < a["backlog_at_end"]
    assert k == run_design(build_site(3, "ch-bank"), d["kit"]["switches"])


def test_ungoverned_triage_loses_customers_the_governed_one_keeps() -> None:
    site = build_site(3, "uk-emi")
    d = config.designs()["designs"]
    g = run_design(site, d["kit"]["switches"])
    u = run_design(site, d["ungoverned_triage"]["switches"])
    assert g["reportable_missed_after_machine_close"] == 0 and u["reportable_missed_after_machine_close"] > 0


def test_heldout_runs_once(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(study, "LOCK", tmp_path / "heldout.lock")
    (tmp_path / "heldout.lock").write_text("{}")
    with pytest.raises(study.HeldOutLocked):
        study.run_heldout_once()


def test_readme_block_is_generated() -> None:
    p = ROOT / "reports" / "dev.json"
    if not p.exists():
        pytest.skip("no report yet")
    assert json.loads(p.read_text())["gates"]["kit_pass"]
    readme = (ROOT / "README.md").read_text()
    assert "<!-- results:start -->" in readme and "Generated by `ocp report`" in readme
